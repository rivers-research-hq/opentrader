import random
from typing import List, Optional


def transform(bars: List[dict], config: Optional[dict] = None) -> List[dict]:
    """Apply risk_management adversarial transform to bars.

    Tests the agent's ability to handle risk management scenarios. Based on: Estimating the covariance structure of financial assets typically relies on his- torical returns, making risk models dependent 
    """
    result = [dict(bar) for bar in bars]
    config = config or {}

    # # Adversarial logic for risk_management:
#   Estimating the covariance structure of financial assets typically relies on his- torical returns, making risk models dep
    intensity = config.get("intensity", 0.1)
    seed = config.get("seed", 42)
    rng = random.Random(seed)

    for i, bar in enumerate(result):
        if rng.random() < intensity:
            # Inject adversarial pattern
            bar["close"] = bar["close"] * (1.0 + rng.uniform(-0.02, 0.02))
            bar["high"] = max(bar["high"], bar["close"] * 1.01)
            bar["low"] = min(bar["low"], bar["close"] * 0.99)

    return result
