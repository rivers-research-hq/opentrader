"""Adversarial transform for TraderBench: Trustworthy synthetic data for campaign decision support: strategy simulation fidelity and the Polic
Generated by capability-distiller from arxiv

Tests capability: data_augmentation
"""
import random
from typing import List, Optional


def transform(bars: List[dict], config: Optional[dict] = None) -> List[dict]:
    """Apply data_augmentation adversarial transform to bars.

    Tests the agent's ability to handle data augmentation scenarios. Based on: Decision support systems (DSS) increasingly run retention what-if analysis on synthetic customer populations, because privacy
    """
    result = [dict(bar) for bar in bars]
    config = config or {}

    # # Adversarial logic for data_augmentation:
#   Decision support systems (DSS) increasingly run retention what-if analysis on synthetic customer populations, because pr
    intensity = config.get("intensity", 0.1)
    seed = config.get("seed", 42)
    rng = random.Random(seed)

    for i, bar in enumerate(result):
        if rng.random() < intensity:
            # Inject adversarial pattern
            bar["close"] = bar["close"] * (1.0 + rng.uniform(-0.02, 0.02))
            bar["high"] = max(bar["high"], bar["close"] * 1.01)
            bar["low"] = min(bar["low"], bar["close"] * 0.99)

    return result
