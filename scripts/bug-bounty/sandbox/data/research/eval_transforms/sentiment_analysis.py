import random
from typing import List, Optional


def transform(bars: List[dict], config: Optional[dict] = None) -> List[dict]:
    """Apply sentiment_analysis adversarial transform to bars.

    Tests the agent's ability to handle sentiment analysis scenarios. Based on: The growing use of Bitcoin as a decentralized digital asset and investment tool has sparked strong interest in understanding
    """
    result = [dict(bar) for bar in bars]
    config = config or {}

    # # Adversarial logic for sentiment_analysis:
#   The growing use of Bitcoin as a decentralized digital asset and investment tool has sparked strong interest in understan
    intensity = config.get("intensity", 0.1)
    seed = config.get("seed", 42)
    rng = random.Random(seed)

    for i, bar in enumerate(result):
        if rng.random() < intensity:
            # Inject adversarial pattern
            bar["close"] = bar["close"] * (1.0 + rng.uniform(-0.02, 0.02))
            bar["high"] = max(bar["high"], bar["close"] * 1.01)
            bar["low"] = min(bar["low"], bar["close"] * 0.99)

    return result
